"""Evaluate the agent and two baselines on the human-adjudicated golden set, with an LLM judge.

Stages:
    predict   run every system on the 200 golden examples; write predictions + metrics
    judge     score every auto-handled reply with an independent-family LLM judge
    all       both, in order

Systems (all see only the customer message and TRAIN-split evidence retrieved before it):
    agent_llm        full pipeline, reply generated by openai/gpt-oss-120b
    agent_template   full pipeline, deterministic evidence-template reply (ablation, $0)
    baseline_a       majority intent + always-escalate (the strong safety baseline)
    baseline_b       TF-IDF intent + lexical rules + taxonomy policy routing,
                     reply = nearest historical resolution (no evidence/grounding/LLM gates)

**Read DISCLOSURE in metrics.json before quoting any number.** On the 160 assisted examples
the gold labels match the Llama pre-annotation on 159, accepted at a median of under a second.
All-200 metrics therefore measure agreement with human-accepted model pre-annotation. The 40
blind examples were labelled from scratch and are reported as their own subset.

Judge-human agreement is NOT measured: no human reply-quality ratings exist. It is reported as
unmeasured, never estimated.

Usage:
    python scripts/evaluate_golden.py --stage all --limit 5      # smoke run, separate output
    python scripts/evaluate_golden.py --stage all                 # full run
"""

